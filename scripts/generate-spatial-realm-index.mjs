import { readFile, stat, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const projectRoot = resolve(import.meta.dirname, "..");
const sceneRoot = resolve(projectRoot, "public/data/scenes");
const semanticRoot = resolve(projectRoot, "public/data/semantic");
const outputPath = resolve(projectRoot, "app/domain/spatialLexemeRealms.generated.ts");
const MAX_OUTPUT_BYTES = 16 * 1024;
const VALID_REALMS = new Set([
  "nature-life",
  "body-daily-life",
  "objects-technology",
  "people-society",
  "mind-values",
  "language-culture",
  "actions-events",
  "space-time-measure",
  "qualities-states",
  "grammar-relations",
]);

async function readJson(path) {
  return JSON.parse(await readFile(path, "utf8"));
}

async function generateIndex() {
  const sceneManifest = await readJson(resolve(sceneRoot, "manifest.json"));
  const scenes = await Promise.all(sceneManifest.scenes.map(({ id }) => (
    readJson(resolve(sceneRoot, `${id}.json`))
  )));
  const linkedLabels = scenes.flatMap((scene) => scene.labels.filter(({ lexemeId }) => lexemeId));
  const linkedIds = new Set(linkedLabels.map(({ lexemeId }) => lexemeId));

  const semanticManifest = await readJson(resolve(semanticRoot, "manifest.json"));
  const semanticShards = await Promise.all(semanticManifest.shards.map(({ path }) => (
    readJson(resolve(semanticRoot, path))
  )));
  const realmByLexeme = new Map();
  for (const { nodes } of semanticShards) {
    for (const { id, realmId } of nodes) {
      if (!VALID_REALMS.has(realmId)) throw new Error(`Semantic lexeme ${id} has invalid realm ${realmId}`);
      const previousRealm = realmByLexeme.get(id);
      if (previousRealm && previousRealm !== realmId) {
        throw new Error(`Semantic lexeme ${id} has conflicting realms ${previousRealm} and ${realmId}`);
      }
      realmByLexeme.set(id, realmId);
    }
  }

  const missingIds = [...linkedIds].filter((id) => !realmByLexeme.has(id)).sort();
  if (missingIds.length) {
    throw new Error(`Spatial realm index is missing ${missingIds.length} lexemes: ${missingIds.join(", ")}`);
  }
  const entries = [...linkedIds]
    .sort((left, right) => left.localeCompare(right))
    .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(realmByLexeme.get(id))},`)
    .join("\n");
  const source = `/* This file is generated by scripts/generate-spatial-realm-index.mjs. */
import type { LabelSemanticRealm } from "./labelSemanticStyle";

/** Number of authored spatial label references covered by this compact index. */
export const SPATIAL_LEXEME_LINK_COUNT = ${linkedLabels.length};

/** Bundled realm lookup for spatial labels; it never causes a runtime shard request. */
export const SPATIAL_LEXEME_REALMS = Object.freeze({
${entries}
} as const) satisfies Readonly<Record<string, LabelSemanticRealm>>;
`;
  const bytes = Buffer.byteLength(source);
  if (bytes > MAX_OUTPUT_BYTES) {
    throw new Error(`Spatial realm index is ${bytes} bytes; budget is ${MAX_OUTPUT_BYTES}`);
  }
  return { source, bytes, linkedLabelCount: linkedLabels.length, uniqueLexemeCount: linkedIds.size };
}

const generated = await generateIndex();
if (process.argv.includes("--check")) {
  const existing = await readFile(outputPath, "utf8").catch(() => "");
  if (existing !== generated.source) {
    throw new Error("Spatial realm index is stale; run npm run generate:spatial-realms");
  }
  const outputStat = await stat(outputPath);
  if (outputStat.size > MAX_OUTPUT_BYTES) {
    throw new Error(`Spatial realm index is ${outputStat.size} bytes; budget is ${MAX_OUTPUT_BYTES}`);
  }
  console.log(JSON.stringify({ ...generated, source: undefined, status: "current" }));
} else {
  await writeFile(outputPath, generated.source);
  console.log(JSON.stringify({ ...generated, source: undefined, status: "generated" }));
}
